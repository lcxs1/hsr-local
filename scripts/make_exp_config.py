"""Write a temporary config with one P0 popup experiment enabled.

`config.toml` keeps every experiment off.  The real-client tests need a small
matrix of variants, and hand-editing the file between launches is exactly the
kind of mistake this project cannot afford, so the runner asks this script for a
ready-to-use config under ``logs/exp/``.

    python scripts/make_exp_config.py --preset all
    python scripts/make_exp_config.py --preset activity --activity active

Presets: baseline, mission, quest, activity, activity_active, basicinfo_omit,
basicinfo_nested, core, all.
"""

from __future__ import annotations

import argparse
import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PRESETS: dict[str, dict] = {
    "baseline": {
        "popup_mission": False,
        "popup_quest": False,
        "popup_activity": "off",
        "popup_basic_info": "keep",
        "popup_sdk_config": "disabled",
    },
    "sdk404": {"popup_sdk_config": "notfound"},
    "mission": {"popup_mission": True},
    "quest": {"popup_quest": True},
    "activity": {"popup_activity": "ended"},
    "activity_active": {"popup_activity": "active"},
    "basicinfo_omit": {"popup_basic_info": "omit"},
    "basicinfo_nested": {"popup_basic_info": "nested"},
    "core": {
        "popup_mission": True,
        "popup_quest": True,
        "popup_activity": "ended",
    },
    "all": {
        "popup_mission": True,
        "popup_quest": True,
        "popup_activity": "ended",
        "popup_basic_info": "nested",
        "popup_sdk_config": "disabled",
    },
}


def _fmt(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_fmt(v) for v in value) + "]"
    raise TypeError(f"cannot write {type(value)!r} to toml")


def dump_toml(data: dict) -> str:
    lines = ["# generated by scripts/make_exp_config.py - do not edit by hand", ""]
    for key, value in data.items():
        if isinstance(value, dict):
            lines.append(f"[{key}]")
            lines.extend(f"{k} = {_fmt(v)}" for k, v in value.items())
            lines.append("")
        else:
            lines.append(f"{key} = {_fmt(value)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", type=Path, default=ROOT / "config.toml")
    ap.add_argument("--preset", choices=sorted(PRESETS), default="all")
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--activity", choices=["off", "ended", "active"], default=None)
    ap.add_argument("--basic-info", choices=["keep", "omit", "nested"], default=None)
    ap.add_argument(
        "--no-calyx",
        action="store_true",
        help="remove the calyx group/prop from the static scene (loading-screen test)",
    )
    args = ap.parse_args()

    raw = tomllib.loads(args.base.read_text(encoding="utf-8"))
    experiments = dict(raw.get("experiments", {}))
    experiments.update(PRESETS[args.preset])
    if args.activity:
        experiments["popup_activity"] = args.activity
    if args.basic_info:
        experiments["popup_basic_info"] = args.basic_info
    raw["experiments"] = experiments

    if args.no_calyx:
        world = dict(raw.get("world", {}))
        for key in (
            "calyx_group_id",
            "calyx_inst_id",
            "calyx_entity_id",
            "calyx_prop_id",
            "calyx_x",
            "calyx_y",
            "calyx_z",
        ):
            world[key] = 0
        raw["world"] = world

    out = args.out or ROOT / "logs" / "exp" / f"{args.preset}.toml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(dump_toml(raw), encoding="utf-8")
    print(f"wrote {out}")
    print(f"  world.calyx_group_id = {raw.get('world', {}).get('calyx_group_id')!r}")
    for key in (
        "popup_mission",
        "popup_quest",
        "popup_activity",
        "popup_basic_info",
        "popup_sdk_config",
    ):
        print(f"  {key} = {experiments.get(key)!r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

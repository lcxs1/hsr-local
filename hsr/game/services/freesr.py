"""Data model for `freesr-data.json` (SR Tools / FreeSR format).

This file is generated by an external website. Users replace it manually and
restart the server; there is no hot reload yet.
"""

from __future__ import annotations

import json
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field


class SubAffix(BaseModel):
    count: int = 0
    step: int = 0
    sub_affix_id: int = 0


class Relic(BaseModel):
    equip_avatar: int = 0
    internal_uid: int = 0
    level: int = 0
    main_affix_id: int = 0
    relic_id: int = 0
    relic_set_id: int = 0
    sub_affixes: list[SubAffix] = Field(default_factory=list)


class Lightcone(BaseModel):
    equip_avatar: int = 0
    internal_uid: int = 0
    item_id: int = 0
    level: int = 80
    promotion: int = 6
    rank: int = 1


class DynamicKey(BaseModel):
    key: str = ""
    value: int = 0


class InnerData(BaseModel):
    rank: int = 0
    skills: dict[int, int] = Field(default_factory=dict)
    skills_by_anchor_type: dict[int, int] = Field(default_factory=dict)
    ex_rank_id_list: list[int] = Field(default_factory=list)


class Avatar(BaseModel):
    avatar_id: int = 0
    data: InnerData = Field(default_factory=InnerData)
    level: int = 80
    promotion: int = 6
    sp_max: int = 100
    sp_value: int = 0
    techniques: list[int] = Field(default_factory=list)
    enhanced_id: int = 0


class Monster(BaseModel):
    monster_id: int = 0
    amount: int = 1
    level: int = 80
    cur_hp: int | None = None
    max_hp: int | None = None


class Blessing(BaseModel):
    id: int = 0
    level: int = 1
    dynamic_key: DynamicKey | None = None
    dynamic_values: list[DynamicKey] = Field(default_factory=list)


class BattleConfig(BaseModel):
    battle_type: str | None = None
    blessings: list[Blessing] = Field(default_factory=list)
    custom_stats: list[SubAffix] = Field(default_factory=list)
    monsters: list[list[Monster]] = Field(default_factory=list)
    stage_id: int = 0
    path_resonance_id: int = 0
    cycle_count: int | None = None


class FreesrData(BaseModel):
    model_config = ConfigDict(extra="ignore")

    key: str = ""
    avatars: dict[int, Avatar] = Field(default_factory=dict)
    relics: list[Relic] = Field(default_factory=list)
    lightcones: list[Lightcone] = Field(default_factory=list)
    battle_config: BattleConfig = Field(default_factory=BattleConfig)
    loadout: list[dict] = Field(default_factory=list)


def load(path: str | Path) -> FreesrData:
    # utf-8-sig: the site (and PowerShell `-Encoding UTF8`) may prefix a BOM.
    raw = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    return FreesrData.model_validate(raw)

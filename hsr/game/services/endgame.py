"""Endgame tables: MoC / PF / AS challenges, Peak (异相仲裁) and Tierce.

`data/endgame.json` is generated by ``scripts/export_endgame.py`` from the
4.6.54 client tables (pearl-sr's extracted JSON). One entry per challenge holds
both nodes ("first"/"second" lineup) and the scene ids the client needs; the
``scenes`` section carries the maze groups referenced by those nodes, so the
server can spawn the NPC monster + props without shipping the 26 MB res.json.

Mode split (4.6.54, verified against pearl-sr):

====================  ===================  ==================================
id range              mode                 battle entry
====================  ===================  ==================================
``< 20000``           混沌回忆 (MOC)        ``StartChallengeCsReq``
``20000 .. 29999``    虚构叙事 (PF)         ``StartChallengeCsReq`` + story buffs
``>= 30000``          末日幻影 (AS)         ``StartChallengeCsReq`` + boss buffs
``ChallengePeak``     异相仲裁             ``StartChallengePeakCsReq``
``ChallengeMazeTierce``  Tierce（待真机确认） ``StartChallengeTierceCsReq``
====================  ===================  ==================================

The battle stage id is the **last** ``EventIDList`` entry of the node; the
waves come from the same StageConfig table the cocoon battles use.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from hsr.game.services.battle import StageInfo

log = logging.getLogger("hsr.endgame")

MOC = "MOC"
PF = "PF"
AS = "AS"
CHALLENGE_MODES = (MOC, PF, AS)


def mode_of(challenge_id: int) -> str:
    """4.6.54 id partition; unknown ids are treated as MoC."""
    if challenge_id < 20000:
        return MOC
    if challenge_id < 30000:
        return PF
    return AS


@dataclass
class Season:
    """One rotation of an endgame mode (from the srtools index).

    ``data/endgame.json`` only knows group ids; the vendor index
    (``scripts/import_srtools.py``) adds the season name and its window, which is
    how the server decides *which* group is the current one (1036 = 物竞天择 on
    2026-11-11, 1037 = 漆黑残响 from 2026-12-14).
    """

    group_id: int = 0
    mode: str = MOC
    name: str = ""
    begin: datetime | None = None
    end: datetime | None = None

    def covers(self, at: datetime) -> bool:
        return self.begin is not None and self.end is not None and self.begin <= at <= self.end


def latest_index(data_dir: str | Path) -> Path | None:
    """Newest ``data/vendor/srtools-*/endgame_index.json``, or None."""
    vendor = Path(data_dir) / "vendor"
    candidates = sorted(vendor.glob("srtools-*/endgame_index.json"))
    return candidates[-1] if candidates else None


# --------------------------------------------------------------------- models
@dataclass
class SceneMonster:
    inst_id: int = 0
    monster_id: int = 0
    event_id: int = 0
    pos: tuple[int, int, int] = (0, 0, 0)
    rot: tuple[int, int, int] = (0, 0, 0)


@dataclass
class SceneProp:
    inst_id: int = 0
    prop_id: int = 0
    prop_state: int = 0
    # Lobby entries carry their maze group per prop (one entry spans several
    # groups); inside ``SceneSpec.groups`` this stays 0 and the group owns it.
    group_id: int = 0
    pos: tuple[int, int, int] = (0, 0, 0)
    rot: tuple[int, int, int] = (0, 0, 0)



@dataclass
class SceneGroup:
    group_id: int = 0
    monsters: list[SceneMonster] = field(default_factory=list)
    props: list[SceneProp] = field(default_factory=list)


@dataclass
class SceneSpec:
    plane_id: int = 0
    entry_id: int = 0
    groups: dict[int, SceneGroup] = field(default_factory=dict)


@dataclass
class ChallengeNode:
    """One of the two lineup nodes of a challenge (PF/AS use both)."""

    entrance_id: int = 0
    plane_id: int = 0
    floor_id: int = 0
    world_id: int = 0
    maze_group_id: int = 0
    monster_id: int = 0
    stage_id: int = 0


@dataclass
class Challenge:
    id: int = 0
    mode: str = MOC
    group_id: int = 0
    floor: int = 0
    stage_num: int = 1
    buff_id: int = 0
    target_ids: list[int] = field(default_factory=list)
    countdown: int = 0
    node1: ChallengeNode = field(default_factory=ChallengeNode)
    node2: ChallengeNode | None = None

    def node(self, second: bool = False) -> ChallengeNode:
        if second and self.node2 is not None:
            return self.node2
        return self.node1


@dataclass
class PeakStage:
    id: int = 0
    entrance_id: int = 0
    plane_id: int = 0
    floor_id: int = 0
    world_id: int = 0
    maze_group_id: int = 0
    monster_id: int = 0
    stage_id: int = 0
    tag_ids: list[int] = field(default_factory=list)
    target_ids: list[int] = field(default_factory=list)
    progress: list[int] = field(default_factory=list)
    hp_progress: list[int] = field(default_factory=list)


@dataclass
class PeakGroup:
    id: int = 0
    boss_level_id: int = 0
    pre_level_ids: list[int] = field(default_factory=list)
    reward_group_id: int = 0


@dataclass
class PeakBoss:
    id: int = 0
    buff_ids: list[int] = field(default_factory=list)
    hard_event_ids: list[int] = field(default_factory=list)
    hard_tag_ids: list[int] = field(default_factory=list)
    hard_target: int = 0
    color_medal_target: int = 0


@dataclass
class TierceStage:
    id: int = 0
    entrance_id: int = 0
    plane_id: int = 0
    floor_id: int = 0
    world_id: int = 0
    maze_group_id: int = 0
    monster_id: int = 0
    stage_id: int = 0
    target_ids: list[int] = field(default_factory=list)
    tierce_target_id: int = 0
    pre_challenge_id: int = 0


# ---------------------------------------------------------------------- utils
def _vec(raw: dict | None) -> tuple[int, int, int]:
    raw = raw or {}
    return (int(raw.get("x", 0)), int(raw.get("y", 0)), int(raw.get("z", 0)))


def _time(value) -> datetime | None:
    """``"2026-11-02 04:00:00"`` -> datetime; anything unparsable -> None."""
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value))
    except ValueError:
        return None


def _node(raw: dict | None) -> ChallengeNode | None:
    if not raw:
        return None
    return ChallengeNode(
        entrance_id=int(raw.get("entrance_id", 0)),
        plane_id=int(raw.get("plane_id", 0)),
        floor_id=int(raw.get("floor_id", 0)),
        world_id=int(raw.get("world_id", 0)),
        maze_group_id=int(raw.get("maze_group_id", 0)),
        monster_id=int(raw.get("monster_id", 0)),
        stage_id=int(raw.get("stage_id", 0)),
    )


# ------------------------------------------------------------------ EndgameData
@dataclass
class EndgameData:
    challenges: dict[int, Challenge] = field(default_factory=dict)
    stages: dict[int, StageInfo] = field(default_factory=dict)
    scenes: dict[int, SceneSpec] = field(default_factory=dict)
    # Lobby planes (忘却之庭大厅): plane id -> entry id -> props/monsters.
    lobbies: dict[int, dict[int, list[SceneProp]]] = field(default_factory=dict)
    # Rotation metadata per group id (vendor index; empty when it is not there).
    seasons: dict[int, Season] = field(default_factory=dict)

    floors: dict[int, list[dict]] = field(default_factory=dict)
    anchors: dict[int, dict] = field(default_factory=dict)
    entrances: dict[int, dict] = field(default_factory=dict)
    peak_stages: dict[int, PeakStage] = field(default_factory=dict)
    peak_groups: dict[int, PeakGroup] = field(default_factory=dict)
    peak_bosses: dict[int, PeakBoss] = field(default_factory=dict)
    tierce: dict[int, TierceStage] = field(default_factory=dict)
    source: str = ""
    load_error: str | None = None

    # ------------------------------------------------------------------- load
    @classmethod
    def load(
        cls,
        path: str | Path,
        logger: logging.Logger | None = None,
        seasons_path: str | Path | None = None,
    ) -> EndgameData:
        log_ = logger or log
        data = cls()
        try:
            raw = json.loads(Path(path).read_text(encoding="utf-8-sig"))
        except (OSError, ValueError) as exc:
            log_.warning("failed to load endgame data (%s): %s", path, exc)
            data.load_error = f"{path}: {exc}"
            return data

        data.source = str(path)
        if seasons_path is not None:
            data._load_seasons(Path(seasons_path), log_)
        for key, value in (raw.get("challenges") or {}).items():
            node1 = _node(value.get("node1"))
            if node1 is None:
                continue
            challenge = Challenge(
                id=int(value.get("id", key)),
                mode=str(value.get("mode", mode_of(int(key)))),
                group_id=int(value.get("group_id", 0)),
                floor=int(value.get("floor", 0)),
                stage_num=int(value.get("stage_num", 1) or 1),
                buff_id=int(value.get("buff_id", 0)),
                target_ids=[int(x) for x in (value.get("target_ids") or [])],
                countdown=int(value.get("countdown", 0) or 0),
                node1=node1,
                node2=_node(value.get("node2")),
            )
            data.challenges[challenge.id] = challenge

        for stage_id, value in (raw.get("stages") or {}).items():
            data.stages[int(stage_id)] = StageInfo(
                level=int(value.get("level", 80)),
                waves=[[int(m) for m in wave] for wave in (value.get("waves") or [])],
            )

        for plane_id, value in (raw.get("scenes") or {}).items():
            spec = SceneSpec(
                plane_id=int(plane_id),
                entry_id=int(value.get("entry_id", 0) or 0),
            )
            for group_id, group in (value.get("groups") or {}).items():
                spec.groups[int(group_id)] = SceneGroup(
                    group_id=int(group_id),
                    monsters=[
                        SceneMonster(
                            inst_id=int(m.get("inst_id", 0)),
                            monster_id=int(m.get("monster_id", 0)),
                            event_id=int(m.get("event_id", 0)),
                            pos=_vec(m.get("pos")),
                            rot=_vec(m.get("rot")),
                        )
                        for m in (group.get("monsters") or [])
                    ],
                    props=[
                        SceneProp(
                            inst_id=int(p.get("inst_id", 0)),
                            prop_id=int(p.get("prop_id", 0)),
                            prop_state=int(p.get("prop_state", 0)),
                            pos=_vec(p.get("pos")),
                            rot=_vec(p.get("rot")),
                        )
                        for p in (group.get("props") or [])
                    ],
                )
            data.scenes[spec.plane_id] = spec

        for plane_id, value in (raw.get("lobby") or {}).items():
            entries: dict[int, list[SceneProp]] = {}
            for entry_id, entry in (value.get("entries") or {}).items():
                entries[int(entry_id)] = [
                    SceneProp(
                        inst_id=int(p.get("inst_id", 0)),
                        prop_id=int(p.get("prop_id", 0)),
                        prop_state=int(p.get("prop_state", 0)),
                        group_id=int(p.get("group_id", 0)),
                        pos=_vec(p.get("pos")),
                        rot=_vec(p.get("rot")),
                    )
                    for p in (entry.get("props") or [])
                ]
            if entries:
                data.lobbies[int(plane_id)] = entries

        for floor_id, values in (raw.get("floors") or {}).items():
            data.floors[int(floor_id)] = [
                {"name": str(v.get("name", "")), "value": int(v.get("value", 0))}
                for v in values
            ]
        data.anchors = {int(k): dict(v) for k, v in (raw.get("anchors") or {}).items()}
        data.entrances = {
            int(key): {
                "plane_id": int(value.get("plane_id", 0)),
                "floor_id": int(value.get("floor_id", 0)),
            }
            for key, value in (raw.get("entrances") or {}).items()
        }

        for peak_id, value in (raw.get("peak", {}).get("stages") or {}).items():
            data.peak_stages[int(peak_id)] = PeakStage(
                id=int(value.get("id", peak_id)),
                entrance_id=int(value.get("entrance_id", 0)),
                plane_id=int(value.get("plane_id", 0)),
                floor_id=int(value.get("floor_id", 0)),
                world_id=int(value.get("world_id", 0)),
                maze_group_id=int(value.get("maze_group_id", 0)),
                monster_id=int(value.get("monster_id", 0)),
                stage_id=int(value.get("stage_id", 0)),
                tag_ids=[int(x) for x in (value.get("tag_ids") or [])],
                target_ids=[int(x) for x in (value.get("target_ids") or [])],
                progress=[int(x) for x in (value.get("progress") or [])],
                hp_progress=[int(x) for x in (value.get("hp_progress") or [])],
            )
        for group_id, value in (raw.get("peak", {}).get("groups") or {}).items():
            data.peak_groups[int(group_id)] = PeakGroup(
                id=int(value.get("id", group_id)),
                boss_level_id=int(value.get("boss_level_id", 0)),
                pre_level_ids=[int(x) for x in (value.get("pre_level_ids") or [])],
                reward_group_id=int(value.get("reward_group_id", 0)),
            )
        for boss_id, value in (raw.get("peak", {}).get("bosses") or {}).items():
            data.peak_bosses[int(boss_id)] = PeakBoss(
                id=int(value.get("id", boss_id)),
                buff_ids=[int(x) for x in (value.get("buff_ids") or [])],
                hard_event_ids=[int(x) for x in (value.get("hard_event_ids") or [])],
                hard_tag_ids=[int(x) for x in (value.get("hard_tag_ids") or [])],
                hard_target=int(value.get("hard_target", 0) or 0),
                color_medal_target=int(value.get("color_medal_target", 0) or 0),
            )
        for tierce_id, value in (raw.get("tierce") or {}).items():
            data.tierce[int(tierce_id)] = TierceStage(
                id=int(value.get("id", tierce_id)),
                entrance_id=int(value.get("entrance_id", 0)),
                plane_id=int(value.get("plane_id", 0)),
                floor_id=int(value.get("floor_id", 0)),
                world_id=int(value.get("world_id", 0)),
                maze_group_id=int(value.get("maze_group_id", 0)),
                monster_id=int(value.get("monster_id", 0)),
                stage_id=int(value.get("stage_id", 0)),
                target_ids=[int(x) for x in (value.get("target_ids") or [])],
                tierce_target_id=int(value.get("tierce_target_id", 0) or 0),
                pre_challenge_id=int(value.get("pre_challenge_id", 0) or 0),
            )

        log_.info(
            "endgame loaded: %d challenges (MOC %d / PF %d / AS %d),"
            " peak %d stages, tierce %d, %d stage tables, %d scenes",
            len(data.challenges),
            sum(1 for c in data.challenges.values() if c.mode == MOC),
            sum(1 for c in data.challenges.values() if c.mode == PF),
            sum(1 for c in data.challenges.values() if c.mode == AS),
            len(data.peak_stages),
            len(data.tierce),
            len(data.stages),
            len(data.scenes),
        )
        return data

    # ---------------------------------------------------------------- helpers
    def _load_seasons(self, path: Path, logger: logging.Logger) -> None:
        try:
            raw = json.loads(path.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError) as exc:
            logger.warning("failed to load season index (%s): %s", path, exc)
            return
        for mode, block in (raw.get("modes") or {}).items():
            for group in block.get("groups") or []:
                group_id = int(group.get("id", 0) or 0)
                if not group_id:
                    continue
                self.seasons[group_id] = Season(
                    group_id=group_id,
                    mode=str(mode),
                    name=str(group.get("name", "")),
                    begin=_time(group.get("begin")),
                    end=_time(group.get("end")),
                )
        logger.info("seasons loaded: %d groups from %s", len(self.seasons), path.name)

    def season(self, group_id: int) -> Season | None:
        return self.seasons.get(int(group_id))

    def active_group(self, mode: str, at: datetime | None = None) -> int:
        """Group id of the rotation covering ``at`` (default: now), or 0."""
        now = at or datetime.now()
        for season in self.seasons.values():
            if season.mode == mode and season.covers(now):
                return season.group_id
        return 0

    def challenge(self, challenge_id: int) -> Challenge | None:
        return self.challenges.get(int(challenge_id))

    def stage(self, stage_id: int) -> StageInfo | None:
        return self.stages.get(int(stage_id))

    def scene(self, plane_id: int) -> SceneSpec | None:
        return self.scenes.get(int(plane_id))

    def scene_group(self, plane_id: int, group_id: int) -> SceneGroup | None:
        spec = self.scene(plane_id)
        if spec is None:
            return None
        return spec.groups.get(int(group_id))

    def anchor(self, entry_id: int) -> dict:
        return self.anchors.get(int(entry_id), {})

    def lobby_entry(self, plane_id: int, entry_id: int) -> list[SceneProp] | None:
        """Props of one lobby scene entry (忘却之庭大厅), or None when unknown.

        ``None`` (not ``[]``) means "this plane/entry has no exported data", so
        callers can fall back to the plain open-world assembly instead of
        rendering an empty lobby.
        """
        entries = self.lobbies.get(int(plane_id))
        if not entries:
            return None
        return entries.get(int(entry_id))


    def entrance(self, entry_id: int) -> dict | None:
        """MapEntrance row: ``{"plane_id", "floor_id"}`` or None."""
        return self.entrances.get(int(entry_id))

    def peak_stage(self, peak_id: int) -> PeakStage | None:
        return self.peak_stages.get(int(peak_id))

    def peak_group(self, group_id: int) -> PeakGroup | None:
        return self.peak_groups.get(int(group_id))

    def peak_boss(self, boss_id: int) -> PeakBoss | None:
        return self.peak_bosses.get(int(boss_id))

    def tierce_stage(self, tierce_id: int) -> TierceStage | None:
        return self.tierce.get(int(tierce_id))

    def challenges_for_mode(self, mode: str) -> list[Challenge]:
        return [c for c in self.challenges.values() if c.mode == mode]

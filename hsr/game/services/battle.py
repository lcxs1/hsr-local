"""Battle payloads for the stagnant-shadow calyx (Phase 2).

The client expects a complete ``SceneBattleInfo`` as soon as it starts a cocoon
stage; an empty response makes the calyx prompt do nothing.  The shape below is
the one echium / pearl / ppSR all use (see ``docs/03-玩法实现拆解.md`` §7.2):

    battle_id, world_level, stage_id, rounds_limit, logic_random_seed,
    monster_wave_list[], battle_avatar_list[], buff_list[]

Stage waves come from ``data/stages.json`` (stagnant shadow stages, generated by
``scripts/export_stages.py``); the fallback battle is ``data/battle.json``.
"""

from __future__ import annotations

import json
import secrets
from dataclasses import dataclass, field
from pathlib import Path

from hsr.log import get_logger
from hsr.protocol import pb

log = get_logger("hsr.battle")

FORMAL = pb.AvatarType.AvatarType_AvatarFormalType
ALL_WAVES = 0xFFFFFFFF


@dataclass
class MonsterSpec:
    monster_id: int = 0
    level: int = 80
    amount: int = 1


@dataclass
class StageInfo:
    level: int = 80
    waves: list[list[int]] = field(default_factory=list)


@dataclass
class BattleData:
    battle_id: int = 1
    stage_id: int = 1052106
    cycle_count: int = 30
    world_level: int = 5
    fallback_waves: list[list[MonsterSpec]] = field(default_factory=list)
    stages: dict[int, StageInfo] = field(default_factory=dict)
    cocoon_stage_map: dict[int, int] = field(default_factory=dict)
    # 历战余响：farm element id -> StageID（`StartQuickFarmElementCsReq` 里那个 id）
    farm_element_stage_map: dict[int, int] = field(default_factory=dict)
    farm_element_default_stage: int = 0
    # 调试用：cocoon id -> 凝滞虚影名字（真机对照表，见 docs/03 §7.1）
    cocoon_names: dict[int, str] = field(default_factory=dict)

    @classmethod
    def load(cls, path: Path, stages_path: Path | None = None) -> BattleData:
        data = cls()
        try:
            raw = json.loads(Path(path).read_text(encoding="utf-8"))
            data.battle_id = int(raw.get("battle_id", 1))
            data.stage_id = int(raw.get("stage_id", data.stage_id))
            data.cycle_count = int(raw.get("cycle_count", 30))
            data.world_level = int(raw.get("world_level", data.world_level))
            data.fallback_waves = [
                [
                    MonsterSpec(
                        monster_id=int(m["monster_id"]),
                        level=int(m.get("level", 80)),
                        amount=int(m.get("amount", 1)),
                    )
                    for m in wave
                ]
                for wave in raw.get("monster_waves", [])
            ]
            data.cocoon_stage_map = {
                int(cocoon_id): int(stage_id)
                for cocoon_id, stage_id in raw.get("cocoon_stage_map", {}).items()
            }
            data.farm_element_stage_map = {
                int(farm_id): int(stage_id)
                for farm_id, stage_id in raw.get("farm_element_stage_map", {}).items()
            }
            data.farm_element_default_stage = int(
                raw.get("farm_element_default_stage", 0) or 0
            )
            data.cocoon_names = {
                int(cocoon_id): str(name)
                for cocoon_id, name in raw.get("cocoon_names", {}).items()
            }
        except (OSError, ValueError, KeyError, TypeError) as exc:
            log.warning("failed to load battle config (%s): %s", path, exc)

        if stages_path is not None:
            try:
                raw_stages = json.loads(Path(stages_path).read_text(encoding="utf-8"))
                data.stages = {
                    int(stage_id): StageInfo(
                        level=int(info.get("level", 80)),
                        waves=[[int(m) for m in wave] for wave in info.get("waves", [])],
                    )
                    for stage_id, info in raw_stages.get("stages", {}).items()
                }
            except (OSError, ValueError, KeyError, TypeError) as exc:
                log.warning("failed to load stage data (%s): %s", stages_path, exc)

        log.info(
            "battle data loaded: %d stages, default stage %d",
            len(data.stages),
            data.stage_id,
        )
        return data

    # ---------------------------------------------------------------- resolve
    def name_of_cocoon(self, cocoon_id: int) -> str:
        return self.cocoon_names.get(cocoon_id, "")

    def level_variant(self, stage_id: int, world_level: int) -> int:
        """Pick the ``world_level`` variant of a cocoon stage.

        A stagnant shadow has 7 StageIDs for world levels 0..6 that differ only in
        level (26/34/42/50/58/68/82) — e.g. ``1052100``..``1052106`` for 二相乐园.
        ``cocoon_stage_map`` stores the top variant; when the client tells us its
        world level we shift to the matching one so the fight level matches what
        the guide recommends.  Unknown levels keep the mapped stage.
        """
        if world_level <= 0:
            return stage_id
        base = stage_id - stage_id % 10
        candidate = base + min(int(world_level), 6)
        return candidate if candidate in self.stages else stage_id

    def resolve_stage(self, cocoon_id: int, world_level: int = 0) -> int:
        """Map the client's cocoon id to a StageID.

        Real client: ``cocoon_id=1014`` for the stagnant shadow on plane 20313
        (logged 2026-11-08); the 「生存指南」quick-start list uses ``1301``..``1310``
        (10 stagnant shadows, logged 2026-11-10 with their boss names).
        ``cocoon_stage_map`` in ``data/battle.json`` holds the mapping; when the id
        already *is* a stage id (e.g. 1052100) it is used directly.
        """
        if cocoon_id in self.cocoon_stage_map:
            return self.level_variant(self.cocoon_stage_map[cocoon_id], world_level)
        if cocoon_id in self.stages:
            return cocoon_id
        log.warning(
            "cocoon %d has no stage mapping; using default stage %d",
            cocoon_id,
            self.stage_id,
        )
        return self.stage_id

    def resolve_farm_stage(self, farm_element_id: int, world_level: int = 0) -> int:
        """Map a 历战余响 (Echo of War) farm element id to a StageID.

        The real ``FarmElementConfig.json`` is keyed by ``(ID, WorldLevel)``.  We do
        not ship that table yet, so ``data/battle.json`` carries a flat
        ``farm_element_stage_map`` filled in from real-client logs; unknown ids fall
        back to ``farm_element_default_stage`` (logged, and the client still gets a
        playable battle instead of a black screen).  ``world_level`` is accepted so
        the signature matches the real table; the flat map ignores it.
        """
        if farm_element_id in self.farm_element_stage_map:
            return self.farm_element_stage_map[farm_element_id]
        if farm_element_id in self.stages:
            return farm_element_id
        fallback = self.farm_element_default_stage or self.stage_id
        log.warning(
            "farm element %d (world_level=%d) has no stage mapping; using default stage %d",
            farm_element_id,
            world_level,
            fallback,
        )
        return fallback

    def next_battle_id(self, session) -> int:
        """Return a fresh battle id for every attempt.

        The client keeps the battle it just settled in an internal map keyed by
        ``battle_id``.  Reusing the same id makes the "battle again" button
        return to the settlement screen instead of loading a new fight, so each
        start gets a new id (the first one still comes from ``battle.json``).
        """
        previous = int(getattr(session, "battle_seq", 0) or 0)
        # battle.json 的 battle_id 若被配成 0/负，首次会返回非法 id 且永不增长；
        # 归一化到 >=1，保证「再来一次」能拿到递增的 id。
        base = max(1, int(self.battle_id or 0))
        value = base if previous <= 0 else previous + 1
        if value > 0xFFFFFFFF:
            value = 1
        session.battle_seq = value
        return value

    # --------------------------------------------------------------- builders
    def monster_waves(self, stage_id: int) -> list[pb.SceneMonsterWave]:
        stage = self.stages.get(stage_id)
        if stage and stage.waves:
            return [
                pb.SceneMonsterWave(
                    battle_wave_id=index + 1,
                    monster_param=pb.SceneMonsterWaveParam(level=stage.level),
                    monster_list=[pb.SceneMonster(monster_id=mid) for mid in wave],
                )
                for index, wave in enumerate(stage.waves)
            ]

        waves: list[pb.SceneMonsterWave] = []
        for index, wave in enumerate(self.fallback_waves):
            level = max((m.level for m in wave), default=80)
            monsters = []
            for monster in wave:
                monsters.extend(
                    pb.SceneMonster(monster_id=monster.monster_id)
                    for _ in range(max(1, monster.amount))
                )
            waves.append(
                pb.SceneMonsterWave(
                    battle_wave_id=index + 1,
                    monster_param=pb.SceneMonsterWaveParam(level=level),
                    monster_list=monsters,
                )
            )
        return waves

    def build_battle_info(
        self,
        session,
        *,
        stage_id: int | None = None,
        world_level: int | None = None,
        battle_id: int | None = None,
    ) -> pb.SceneBattleInfo:
        stage_id = stage_id or self.stage_id
        info = pb.SceneBattleInfo(
            battle_id=battle_id or self.battle_id,
            world_level=world_level or self.world_level,
            stage_id=stage_id,
            rounds_limit=self.cycle_count or 30,
            logic_random_seed=secrets.randbits(32) or 123456789,
        )
        info.monster_wave_list.extend(self.monster_waves(stage_id))
        info.battle_avatar_list.extend(build_battle_avatars(session))
        info.buff_list.extend(build_technique_buffs(session))
        log.info(
            "battle info: id=%d stage=%d waves=%d avatars=%d buffs=%d",
            info.battle_id,
            stage_id,
            len(info.monster_wave_list),
            len(info.battle_avatar_list),
            len(info.buff_list),
        )
        return info


def _battle_avatar(roster, form, index: int, world_level: int) -> pb.BattleAvatar:
    """One BattleAvatar: identity + skills + equipment for the fight.

    ``hp=10000`` is a placeholder carried over from the reference servers, not a
    real stat: this server never simulates the fight, so the client computes
    damage from its own data and only needs the field to be non-zero.  Skills are
    the unlocked ones from freesr (``skills`` or ``skills_by_anchor_type``),
    relics/lightcone are looked up by base id via the roster.
    """
    avatar = pb.BattleAvatar(
        index=index,
        avatar_type=FORMAL,
        id=form.avatar_id,
        level=form.level,
        promotion=form.promotion,
        rank=form.data.rank,
        enhanced_id=form.enhanced_id or 0,
        hp=10000,
        world_level=world_level,
    )
    avatar.sp_bar.CopyFrom(pb.SpBarInfo(cur_sp=form.sp_value or 100, max_sp=form.sp_max or 100))

    skills = form.data.skills or form.data.skills_by_anchor_type
    for point_id, level in skills.items():
        if level > 0:
            avatar.skilltree_list.append(pb.AvatarSkillTree(point_id=point_id, level=level))

    lightcone = roster.lightcone_for(form.avatar_id)
    if lightcone is not None:
        avatar.equipment_list.append(
            pb.BattleEquipment(
                id=lightcone.item_id,
                level=lightcone.level,
                promotion=lightcone.promotion,
                rank=lightcone.rank,
            )
        )
    for relic in roster.relics_for(form.avatar_id):
        avatar.relic_list.append(
            pb.BattleRelic(
                id=relic.relic_id,
                level=relic.level,
                main_affix_id=relic.main_affix_id,
                unique_id=relic.internal_uid,
                set_id=relic.relic_set_id,
                sub_affix_list=[
                    pb.RelicAffix(affix_id=sub.sub_affix_id, cnt=sub.count, step=sub.step)
                    for sub in relic.sub_affixes
                ],
            )
        )
    if form.data.ex_rank_id_list:
        avatar.ExRankList.extend(form.data.ex_rank_id_list)
    return avatar


def build_battle_avatars(session, avatars: list[int] | None = None) -> list[pb.BattleAvatar]:
    """Battle avatars for the team.

    ``avatars`` lets a challenge use the lineup the client sent in
    ``StartChallengeCsReq`` (base ids); without it the session lineup is used.
    """
    roster = session.runtime.roster
    world_level = session.runtime.cfg.player.world_level
    team_size = getattr(session.runtime.cfg.world, "team_size", 4)
    if avatars:
        slots = [int(avatar_id) for avatar_id in avatars[:team_size] if avatar_id]
    else:
        slots = [slot for slot in session.lineup.slots[:team_size] if slot]
        if not slots:
            slots = roster.default_lineup()[:team_size]

    avatars: list[pb.BattleAvatar] = []
    for index, base in enumerate(slots):
        form = roster.preferred_form(
            base,
            tb_path=getattr(session, "tb_multi_path", None),
            march_path=getattr(session, "march_multi_path", None),
        )
        if form is None:
            log.warning("battle avatar %d not found in roster, skipping", base)
            continue
        avatars.append(_battle_avatar(roster, form, index, world_level))
    return avatars


def build_technique_buffs(session) -> list[pb.BattleBuff]:
    """Techniques the team used before the fight, as battle buffs.

    ``id = avatar_id * 100 + 1`` is the generic technique buff id used by all
    three reference servers; ``SkillIndex`` keeps the client from dividing by
    an empty map.
    """
    roster = session.runtime.roster
    team_size = getattr(session.runtime.cfg.world, "team_size", 4)
    slots = [slot for slot in session.lineup.slots[:team_size] if slot]
    if not slots:
        slots = roster.default_lineup()[:team_size]

    buffs: list[pb.BattleBuff] = []
    for index, base in enumerate(slots):
        form = roster.preferred_form(
            base,
            tb_path=getattr(session, "tb_multi_path", None),
            march_path=getattr(session, "march_multi_path", None),
        )
        if form is None:
            continue
        for tech in form.techniques:
            if not tech:
                continue
            buffs.append(
                pb.BattleBuff(
                    id=tech,
                    level=1,
                    owner_index=index,
                    wave_flag=ALL_WAVES,
                    dynamic_values={"SkillIndex": 2.0},
                )
            )
    return buffs
